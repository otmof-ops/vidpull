"""Cookie stores for the tests: a Firefox profile and a Chromium-family profile, written the
way the browsers write them, so yt-dlp's own readers read them. No real browser is touched."""

from __future__ import annotations

import sqlite3
import time
from pathlib import Path

NETSCAPE_HEADER = "# Netscape HTTP Cookie File\n# This file is generated by a test.\n\n"


def youtube_rows(*, signed_in: bool) -> list[tuple[str, str, str]]:
    """(host, name, value) rows: a YouTube sign-in, or a visit without one."""
    rows = [(".youtube.com", "PREF", "tz=UTC"), (".youtube.com", "VISITOR_INFO1_LIVE", "abc")]
    if signed_in:
        rows += [
            (".youtube.com", "LOGIN_INFO", "AFmmF2swRQIgtest"),
            (".youtube.com", "SAPISID", "sapisid-value-1234"),
            (".youtube.com", "__Secure-3PAPISID", "sapisid-value-1234"),
            (".google.com", "SID", "sid-value-5678"),
        ]
    rows.append((".example.com", "session", "other-site"))
    return rows


def firefox_profile(root: Path, *, signed_in: bool = True, name: str = "abcd1234.default") -> Path:
    """``root/<name>/cookies.sqlite`` with ``moz_cookies`` as Firefox 142+ writes it (schema
    16, expiry in milliseconds). Returns the profile folder."""
    profile = root / name
    profile.mkdir(parents=True, exist_ok=True)
    db = profile / "cookies.sqlite"
    db.unlink(missing_ok=True)
    con = sqlite3.connect(db)
    con.execute(
        "CREATE TABLE moz_cookies (id INTEGER PRIMARY KEY, originAttributes TEXT NOT NULL "
        "DEFAULT '', name TEXT, value TEXT, host TEXT, path TEXT, expiry INTEGER, "
        "lastAccessed INTEGER, creationTime INTEGER, isSecure INTEGER, isHttpOnly INTEGER, "
        "inBrowserElement INTEGER DEFAULT 0, sameSite INTEGER DEFAULT 0, "
        "schemeMap INTEGER DEFAULT 0, isPartitionedAttributeSet INTEGER DEFAULT 0)"
    )
    con.execute("PRAGMA user_version = 16")
    expiry = int((time.time() + 180 * 86400) * 1000)
    for host, cookie, value in youtube_rows(signed_in=signed_in):
        con.execute(
            "INSERT INTO moz_cookies (name, value, host, path, expiry, isSecure, isHttpOnly) "
            "VALUES (?, ?, ?, '/', ?, 1, 0)",
            (cookie, value, host, expiry),
        )
    con.commit()
    con.close()
    (root / "profiles.ini").write_text(
        f"[Profile0]\nName=default\nIsRelative=1\nPath={name}\nDefault=1\n"
    )
    return profile


def chromium_profile(root: Path, *, signed_in: bool = True, keyring: bool = False) -> Path:
    """``root/Default/Cookies`` as a Chromium-family browser writes it on Linux: values
    encrypted v10 (the fixed ``peanuts`` key, what ``--password-store=basic`` gives), or v11
    (a keyring's key, which no test can read) when ``keyring``. Returns the database."""
    from yt_dlp.aes import aes_cbc_encrypt_bytes
    from yt_dlp.cookies import pbkdf2_sha1

    key = pbkdf2_sha1(b"peanuts", salt=b"saltysalt", iterations=1, key_length=16)
    profile = root / "Default"
    profile.mkdir(parents=True, exist_ok=True)
    db = profile / "Cookies"
    db.unlink(missing_ok=True)
    con = sqlite3.connect(db)
    con.execute(
        "CREATE TABLE meta (key LONGVARCHAR NOT NULL UNIQUE PRIMARY KEY, value LONGVARCHAR)"
    )
    con.execute("INSERT INTO meta VALUES ('version', '20')")
    con.execute(
        "CREATE TABLE cookies (creation_utc INTEGER NOT NULL, host_key TEXT NOT NULL, "
        "top_frame_site_key TEXT NOT NULL DEFAULT '', name TEXT NOT NULL, value TEXT NOT NULL, "
        "encrypted_value BLOB NOT NULL, path TEXT NOT NULL, expires_utc INTEGER NOT NULL, "
        "is_secure INTEGER NOT NULL, is_httponly INTEGER NOT NULL, last_access_utc INTEGER "
        "NOT NULL, has_expires INTEGER NOT NULL, is_persistent INTEGER NOT NULL, priority "
        "INTEGER NOT NULL, samesite INTEGER NOT NULL, source_scheme INTEGER NOT NULL, "
        "source_port INTEGER NOT NULL, last_update_utc INTEGER NOT NULL, source_type INTEGER "
        "NOT NULL DEFAULT 0, has_cross_site_ancestor INTEGER NOT NULL DEFAULT 0)"
    )
    # Chromium keeps an expiry as microseconds since 1601-01-01
    expires_utc = int((time.time() + 11644473600 + 400 * 86400) * 1_000_000)
    for host, cookie, value in youtube_rows(signed_in=signed_in):
        prefix = b"v11" if keyring else b"v10"
        encrypted = prefix + aes_cbc_encrypt_bytes(value.encode(), key, b" " * 16)
        con.execute(
            "INSERT INTO cookies VALUES (1, ?, '', ?, '', ?, '/', ?, 1, 0, 1, 1, 1, 1, 0, 2, "
            "443, 1, 0, 0)",
            (host, cookie, encrypted, expires_utc),
        )
    con.commit()
    con.close()
    return db


def netscape_file(path: Path, *, signed_in: bool = True) -> Path:
    """A ``cookies.txt`` as a browser extension exports it."""
    expiry = int(time.time() + 180 * 86400)
    lines = [NETSCAPE_HEADER]
    for host, cookie, value in youtube_rows(signed_in=signed_in):
        lines.append(f"{host}\tTRUE\t/\tTRUE\t{expiry}\t{cookie}\t{value}\n")
    path.write_text("".join(lines))
    return path
